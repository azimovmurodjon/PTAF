package com.ptaf.copilot;

import java.nio.file.Path;
import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Validates generated Copilot instruction boundaries before any consumer-repository file is written.
 */
public final class CopilotProfileValidator {
    static final String REPOSITORY_INSTRUCTION_PATH = ".github/copilot-instructions.md";
    static final String PATH_INSTRUCTION_DIRECTORY = ".github/instructions/";
    static final String GENERATED_MARKER = "<!-- GENERATED BY FNB-ETAF COPILOT PROFILE";

    private static final Pattern BEARER_SECRET = Pattern.compile("(?i)bearer\\s+[a-z0-9._~+\\-/]{16,}");
    private static final Pattern JWT_SECRET = Pattern.compile("eyJ[a-zA-Z0-9_-]{10,}\\.[a-zA-Z0-9_-]{10,}\\.[a-zA-Z0-9_-]{10,}");
    private static final Pattern LITERAL_HTTP_ENDPOINT = Pattern.compile("https?://(?!<approved-target>|<example>|example\\.invalid)[^\\s)]+", Pattern.CASE_INSENSITIVE);

    private CopilotProfileValidator() {
        // Utility class.
    }

    /**
     * Ensures the central profile can only generate approved IntelliJ/GitHub Copilot instruction files.
     *
     * @param profile profile to validate
     */
    public static void validate(CopilotProfile profile) {
        if (profile == null) {
            throw new CopilotProfileException("Copilot profile must not be null.");
        }

        validateContent(profile.repositoryInstruction(), REPOSITORY_INSTRUCTION_PATH);
        for (var entry : profile.pathInstructions().entrySet()) {
            validateInstructionPath(entry.getKey());
            validateContent(entry.getValue(), entry.getKey());
            if (!entry.getValue().startsWith("---\n") || !entry.getValue().contains("\n---\n")) {
                throw new CopilotProfileException("Path-specific instruction must begin with YAML front matter: "
                        + entry.getKey());
            }
            if (!entry.getValue().contains("applyTo:")) {
                throw new CopilotProfileException("Path-specific instruction must define applyTo front matter: "
                        + entry.getKey());
            }
        }
        if (profile.discoveryPolicy() != null) {
            validateDiscoveryPolicy(profile.discoveryPolicy());
        }
    }

    /**
     * Checks a consumer-root relative output path before a filesystem operation.
     *
     * @param relativePath generated output path
     */
    public static void validateInstructionPath(String relativePath) {
        if (relativePath == null || relativePath.isBlank()) {
            throw new CopilotProfileException("Copilot instruction output path must not be blank.");
        }

        Path normalized = Path.of(relativePath).normalize();
        String normalizedText = normalized.toString().replace('\\', '/');
        if (normalized.isAbsolute() || normalizedText.equals("..") || normalizedText.startsWith("../")) {
            throw new CopilotProfileException("Copilot instruction path escapes the consumer repository: " + relativePath);
        }
        if (REPOSITORY_INSTRUCTION_PATH.equals(normalizedText)) {
            return;
        }
        if (!normalizedText.startsWith(PATH_INSTRUCTION_DIRECTORY)
                || !normalizedText.endsWith(".instructions.md")) {
            throw new CopilotProfileException("Copilot may write only " + REPOSITORY_INSTRUCTION_PATH + " or "
                    + PATH_INSTRUCTION_DIRECTORY + "*.instructions.md. Rejected: " + relativePath);
        }
    }

    private static void validateContent(String content, String path) {
        String normalized = content == null ? "" : content;
        String lower = normalized.toLowerCase(Locale.ROOT);
        if (BEARER_SECRET.matcher(normalized).find() || JWT_SECRET.matcher(normalized).find()) {
            throw new CopilotProfileException("Copilot instruction contains a token-like value and was rejected: " + path);
        }
        if (LITERAL_HTTP_ENDPOINT.matcher(normalized).find()) {
            throw new CopilotProfileException("Copilot instruction contains a literal HTTP endpoint and was rejected: " + path);
        }
        if (lower.contains("password:") || lower.contains("token:") || lower.contains("secret:")
                || lower.contains("authorization:")) {
            throw new CopilotProfileException("Copilot instruction contains a sensitive configuration assignment and was rejected: "
                    + path);
        }
    }

    private static void validateDiscoveryPolicy(CopilotDiscoveryPolicy policy) {
        if (!policy.defaultHeadless()) {
            throw new CopilotProfileException("The governed local Playwright MCP policy requires default_headless: true.");
        }
        if (policy.mcpTemplateOutputPath().equals(policy.draftOutputDirectory())
                || policy.mcpTemplateOutputPath().startsWith(policy.draftOutputDirectory() + "/")) {
            throw new CopilotProfileException("The local MCP template output path must not be inside the discovery draft directory.");
        }
        if (!policy.allowsAction("click") || !policy.allowsAction("verify_visible")) {
            throw new CopilotProfileException("Discovery policy must permit the baseline click and verify_visible review actions.");
        }
    }
}
